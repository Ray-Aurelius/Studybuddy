"""Generates the Sophinity icon as an Android vector drawable and a matching SVG."""
import math, sys
OUT_RES = sys.argv[1]; OUT_SVG = sys.argv[2]
CX, CY, R = 54.0, 55.0, 25.5
GOLD, GOLD2, STEM = "#FFD23F", "#F5B800", "#E0A800"
PAGE_L, PAGE_R = "#FFFFFF", "#E3F1FF"

def pt(deg, r=R):
    a = math.radians(deg); return CX + r*math.cos(a), CY + r*math.sin(a)

leaves = []  # (x, y, rotation, color)
def branch(a0, a1, n, side):
    for i in range(n):
        t = i/(n-1); deg = a0 + (a1-a0)*t
        tang = deg + 90*side
        for k, off in enumerate((-2.6, 2.6)):           # leaf pairs: inner and outer
            x, y = pt(deg, R+off)
            rot = tang + (32 if off > 0 else -32)*side
            leaves.append((x, y, rot, GOLD if (i+k) % 2 == 0 else GOLD2))
branch(112, 244, 9, +1)   # left branch: bottom → top-left
branch(68, -64, 9, -1)    # right branch: bottom → top-right

def arc_path(a0, a1):
    x0, y0 = pt(a0); x1, y1 = pt(a1)
    sweep = 1 if a1 > a0 else 0
    return f"M{x0:.2f},{y0:.2f} A{R},{R} 0 0,{sweep} {x1:.2f},{y1:.2f}"

LEAF = "M0,-4.4 C2.2,-2.5 2.2,2.5 0,4.4 C-2.2,2.5 -2.2,-2.5 0,-4.4 Z"
BOOK_L = "M53,52 C48,48.8 43,48 38.5,49 L38.5,67 C43,66 48,66.8 53,70 Z"
BOOK_R = "M55,52 C60,48.8 65,48 69.5,49 L69.5,67 C65,66 60,66.8 55,70 Z"
STAR = "M54,33 Q54.9,37.6 59,38.5 Q54.9,39.4 54,44 Q53.1,39.4 49,38.5 Q53.1,37.6 54,33 Z"
stems = [arc_path(106, 246), arc_path(74, -66)]

# ---------- Android vector drawables ----------
fg = ['<?xml version="1.0" encoding="utf-8"?>',
      '<!-- Generated by make_icon.py: laurel wreath around an open book, with a spark of insight. -->',
      '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
for d in stems:
    fg.append(f'  <path android:strokeColor="{STEM}" android:strokeWidth="1.4" android:strokeLineCap="round" android:pathData="{d}" />')
for x, y, rot, c in leaves:
    fg.append(f'  <group android:translateX="{x:.2f}" android:translateY="{y:.2f}" android:rotation="{rot:.1f}"><path android:fillColor="{c}" android:pathData="{LEAF}" /></group>')
fg += [f'  <path android:fillColor="{PAGE_L}" android:pathData="{BOOK_L}" />',
       f'  <path android:fillColor="{PAGE_R}" android:pathData="{BOOK_R}" />',
       f'  <path android:fillColor="{GOLD}" android:pathData="{STAR}" />',
       '</vector>']
open(f"{OUT_RES}/drawable/ic_launcher_foreground.xml", "w").write("\n".join(fg) + "\n")

bg = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Aegean blue to sea teal. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF2F9BFF" />
                <item android:offset="1" android:color="#FF14A8A6" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
open(f"{OUT_RES}/drawable/ic_launcher_background.xml", "w").write(bg)

# ---------- SVG (same geometry) ----------
svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">',
       '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#2F9BFF"/><stop offset="1" stop-color="#14A8A6"/></linearGradient></defs>',
       '<rect width="108" height="108" fill="url(#g)"/>']
for d in stems: svg.append(f'<path d="{d}" fill="none" stroke="{STEM}" stroke-width="1.4" stroke-linecap="round"/>')
for x, y, rot, c in leaves: svg.append(f'<path d="{LEAF}" fill="{c}" transform="translate({x:.2f} {y:.2f}) rotate({rot:.1f})"/>')
svg += [f'<path d="{BOOK_L}" fill="{PAGE_L}"/>', f'<path d="{BOOK_R}" fill="{PAGE_R}"/>', f'<path d="{STAR}" fill="{GOLD}"/>', '</svg>']
open(OUT_SVG, "w").write("\n".join(svg) + "\n")
print("leaves:", len(leaves))
