#!/usr/bin/env python3
"""
Sophinity translation pipeline.

  python3 tools/i18n/i18n.py export   # writes translations/en.txt from res/values/strings.xml
  python3 tools/i18n/i18n.py build    # validates translations/*.txt and writes res/values-xx/strings.xml

Translation files are plain text, one entry per line, easy for reviewers to edit:
  key = Translated text with %1$s placeholders kept exactly
  plural_key.one = %d book
  plural_key.other = %d books
Lines starting with # are comments.
"""
import re, sys, os, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, 'app/src/main/res')
TR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'translations')

# file name -> Android resource qualifier
LOCALES = {
    'es': 'es', 'pt-BR': 'pt-rBR', 'fr': 'fr', 'de': 'de', 'it': 'it', 'nl': 'nl', 'pl': 'pl', 'ru': 'ru',
    'uk': 'uk', 'el': 'el', 'tr': 'tr', 'ar': 'ar', 'hi': 'hi', 'id': 'in', 'vi': 'vi', 'th': 'th',
    'ja': 'ja', 'ko': 'ko', 'zh-CN': 'zh-rCN', 'zh-TW': 'zh-rTW',
}
# CLDR plural categories each language needs
PLURAL_FORMS = {
    'en': ['one', 'other'], 'es': ['one', 'many', 'other'], 'pt-BR': ['one', 'many', 'other'],
    'fr': ['one', 'many', 'other'], 'it': ['one', 'many', 'other'], 'de': ['one', 'other'], 'nl': ['one', 'other'],
    'el': ['one', 'other'], 'tr': ['one', 'other'], 'hi': ['one', 'other'],
    'pl': ['one', 'few', 'many', 'other'], 'ru': ['one', 'few', 'many', 'other'], 'uk': ['one', 'few', 'many', 'other'],
    'ar': ['zero', 'one', 'two', 'few', 'many', 'other'],
    'id': ['other'], 'vi': ['other'], 'th': ['other'], 'ja': ['other'], 'ko': ['other'], 'zh-CN': ['other'], 'zh-TW': ['other'],
}
UNTRANSLATABLE = {'app_name'}

def unesc(t):
    t = t.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n')
    if t.startswith('\\@') or t.startswith('\\?'):
        t = t[1:]
    return t.replace('\\\\', '\\')

def esc(t):
    t = t.replace('\\', '\\\\').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    if t.startswith('@') or t.startswith('?'):
        t = '\\' + t
    return t

def read_en():
    tree = ET.parse(os.path.join(RES, 'values/strings.xml'))
    strings, plurals, formatted_false = {}, {}, set()
    for el in tree.getroot():
        name = el.get('name')
        if el.tag == 'string':
            strings[name] = unesc(el.text or '')
            if el.get('formatted') == 'false':
                formatted_false.add(name)
        elif el.tag == 'plurals':
            plurals[name] = {it.get('quantity'): unesc(it.text or '') for it in el}
    return strings, plurals, formatted_false

def placeholders(t):
    return sorted(re.findall(r'%(?:\d+\$)?[sdf]|%%', t))

def read_tr(path):
    out = {}
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if ' = ' not in line:
            raise SystemExit(f'{path}:{n}: expected "key = text"')
        k, v = line.split(' = ', 1)
        out[k.strip()] = v.replace('\\n', '\n')
    return out

def export():
    strings, plurals, _ = read_en()
    with open(os.path.join(TR, 'en.txt'), 'w', encoding='utf-8') as f:
        f.write('# English source. Keep %1$s / %d placeholders and emoji exactly.\n')
        for k, v in strings.items():
            if k in UNTRANSLATABLE: continue
            f.write(f'{k} = {v}\n'.replace('\n\n', '\\n\n') if False else f'{k} = ' + v.replace('\n', '\\n') + '\n')
        for k, forms in plurals.items():
            for q, v in forms.items():
                f.write(f'{k}.{q} = {v}\n')
    print('exported', len(strings), 'strings,', len(plurals), 'plurals')

def build(only=None):
    strings, plurals, formatted_false = read_en()
    problems = []
    for lang, qual in LOCALES.items():
        if only and lang != only: continue
        path = os.path.join(TR, f'{lang}.txt')
        if not os.path.exists(path):
            problems.append(f'{lang}: missing translations file'); continue
        tr = read_tr(path)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 f'<!-- Generated by tools/i18n/i18n.py from translations/{lang}.txt. Edit that file, not this one. -->',
                 '<resources>']
        for k, en in strings.items():
            if k in UNTRANSLATABLE: continue
            if k not in tr:
                problems.append(f'{lang}: missing {k}'); continue
            v = tr[k]
            if placeholders(v) != placeholders(en):
                problems.append(f'{lang}: {k}: placeholders {placeholders(v)} != {placeholders(en)}')
            fmt = ' formatted="false"' if k in formatted_false else ''
            lines.append(f'    <string name="{k}"{fmt}>{esc(v)}</string>')
        for k, forms in plurals.items():
            need = PLURAL_FORMS[lang]
            lines.append(f'    <plurals name="{k}">')
            en_ph = placeholders(forms['other'])
            for q in need:
                key = f'{k}.{q}'
                if key not in tr:
                    problems.append(f'{lang}: missing {key}'); continue
                v = tr[key]
                ph = placeholders(v)
                # The "one"/"zero"/"two" forms may omit the number (e.g. "a day").
                if ph != en_ph and not (q in ('zero', 'one', 'two') and set(ph) <= set(en_ph)):
                    problems.append(f'{lang}: {key}: placeholders {ph} != {en_ph}')
                lines.append(f'        <item quantity="{q}">{esc(v)}</item>')
            lines.append('    </plurals>')
        extra = set(k.split('.')[0] for k in tr) - set(strings) - set(plurals)
        if extra:
            problems.append(f'{lang}: unknown keys {sorted(extra)[:5]}')
        lines.append('</resources>\n')
        d = os.path.join(RES, f'values-{qual}')
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines))
    if problems:
        print('\n'.join(problems[:80]))
        print(f'{len(problems)} problem(s)')
        sys.exit(1)
    print('ok', only or 'all')

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
    export() if cmd == 'export' else build(sys.argv[2] if len(sys.argv) > 2 else None)
