/**
 * Sophinity's own Greek-themed line-art icons (generated by tools/make_glyphs.py).
 * Subjects and custom categories store a glyph name; data saved by earlier versions
 * stored an emoji, which [res] maps to the closest glyph.
 */
object Glyphs {
    const val SUBJECT_DEFAULT = "scroll"
    const val CATEGORY_DEFAULT = "meander"

    /** Offered when creating or editing a subject. */
    val subjectChoices = listOf(
        "scroll", "alpha_omega", "gear", "coin", "scales", "armillary", "broken_column", "butterfly",
        "amphora", "lyre", "asclepius", "quill", "owl", "ship", "olive", "shield",
        "anvil", "kylix", "stars", "eye", "lamp", "sprout", "columns", "tablet",
    )

    /** Offered when creating or editing a custom library category. */
    val categoryChoices = listOf(
        "meander", "masks", "theatre", "stoa", "tablet", "papyrus", "scroll", "lyre", "lamp", "anvil",
        "amphora", "ship", "armillary", "olive", "kylix", "wheel", "waves", "stadium", "mosaic", "owl",
    )

    /** Emoji stored by versions before 1.5, mapped to the glyph that best keeps their meaning. */
    private val legacy = mapOf(
        // subjects
        "📘" to "scroll", "🧪" to "armillary", "🧮" to "columns", "💻" to "gear", "🌍" to "owl", "🎨" to "amphora",
        "🎵" to "lyre", "🗣️" to "alpha_omega", "🗣" to "alpha_omega", "💼" to "coin", "🧠" to "butterfly",
        "📜" to "broken_column", "⚕️" to "asclepius", "⚕" to "asclepius", "🏋️" to "shield", "🏋" to "shield",
        "🍳" to "kylix", "📷" to "eye", "✍️" to "quill", "✍" to "quill", "🔧" to "anvil", "💰" to "scales",
        "🌱" to "sprout", "🧘" to "lamp",
        // custom categories
        "📌" to "meander", "🛠️" to "anvil", "🛠" to "anvil", "🎭" to "masks", "🎞️" to "theatre", "🎞" to "theatre",
        "🧑‍🏫" to "stoa", "🗺️" to "ship", "🗺" to "ship", "🔬" to "armillary", "🧩" to "mosaic", "📝" to "papyrus",
        "💬" to "waves", "🏛️" to "stoa", "🏛" to "stoa", "🌐" to "wheel", "🎹" to "lyre", "🏃" to "stadium",
        "🌿" to "olive", "🐾" to "owl",
        // built-in library types
        "📚" to "scroll", "🎧" to "lyre", "🎙️" to "masks", "🎤" to "stoa", "🎓" to "tablet", "🎬" to "theatre", "📰" to "papyrus",
    )

    /** Normalizes a stored value (glyph name or legacy emoji) to a glyph name. */
    fun name(stored: String?, fallback: String = SUBJECT_DEFAULT): String = when {
        stored == null -> fallback
        stored in glyphDrawables -> stored
        else -> legacy[stored] ?: legacy[stored.replace("️", "")] ?: fallback
    }

    @DrawableRes
    fun res(stored: String?, fallback: String = SUBJECT_DEFAULT): Int = glyphDrawables.getValue(name(stored, fallback))
}

/** One glyph, tinted like an icon. Decorative unless [contentDescription] is given. */
@Composable
fun Glyph(
    name: String?,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
    contentDescription: String? = null,
    fallback: String = Glyphs.SUBJECT_DEFAULT,
) {
    Icon(painterResource(Glyphs.res(name, fallback)), contentDescription, modifier.size(size), tint = tint)
}

/** A glyph on a soft round tile, used for library items and list rows. */
@Composable
fun GlyphTile(
    name: String?,
    modifier: Modifier = Modifier,
    size: Dp = 40.dp,
    container: Color = MaterialTheme.colorScheme.secondaryContainer,
    tint: Color = MaterialTheme.colorScheme.onSecondaryContainer,
    fallback: String = Glyphs.SUBJECT_DEFAULT,
) {
    Box(modifier.size(size).clip(CircleShape).background(container), contentAlignment = Alignment.Center) {
        Glyph(name, size = size * 0.58f, tint = tint, fallback = fallback)
    }
}

/**
 * A laurel medallion: the glyph on a gold disc inside a laurel wreath once earned,
 * a quiet outline while still ahead.
 */
@Composable
fun LaurelMedal(glyph: String, earned: Boolean, modifier: Modifier = Modifier, size: Dp = 56.dp) {
    val gold = LocalGold.current
    val scheme = MaterialTheme.colorScheme
    Box(modifier.size(size), contentAlignment = Alignment.Center) {
        Icon(
            painterResource(R.drawable.gl_wreath), null, Modifier.fillMaxSize(),
            tint = if (earned) gold.ink else scheme.outlineVariant,
        )
        // The wreath's open centre sits a touch above the middle of its 24-unit grid.
        Box(
            Modifier.offset(y = -size * 0.025f).size(size * 0.44f).clip(CircleShape)
                .background(if (earned) gold.container else scheme.surfaceContainerHigh),
            contentAlignment = Alignment.Center,
        ) {
            Glyph(glyph, size = size * 0.29f, tint = if (earned) gold.onContainer else scheme.onSurfaceVariant.copy(alpha = 0.55f))
        }
    }
}

/** Grid of glyph choices; [selected] may be a legacy emoji, which is matched to its glyph. */
@OptIn(androidx.compose.foundation.layout.ExperimentalLayoutApi::class)
@Composable
fun GlyphPicker(choices: List<String>, selected: String?, onPick: (String) -> Unit, tint: Color = MaterialTheme.colorScheme.onSurface, fallback: String = Glyphs.SUBJECT_DEFAULT) {
    val current = Glyphs.name(selected, fallback)
    androidx.compose.foundation.layout.FlowRow(
        horizontalArrangement = androidx.compose.foundation.layout.Arrangement.spacedBy(4.dp),
        verticalArrangement = androidx.compose.foundation.layout.Arrangement.spacedBy(4.dp),
    ) {
        choices.forEachIndexed { i, g ->
            val sel = g == current
            val label = androidx.compose.ui.res.stringResource(R.string.icon_n, i + 1)
            Box(
                Modifier.size(44.dp).clip(MaterialTheme.shapes.small)
                    .background(if (sel) MaterialTheme.colorScheme.primaryContainer else Color.Transparent)
                    .then(if (sel) Modifier.border(2.dp, MaterialTheme.colorScheme.primary, MaterialTheme.shapes.small) else Modifier)
                    .selectable(selected = sel, role = androidx.compose.ui.semantics.Role.RadioButton) { onPick(g) }
                    .semantics { contentDescription = label },
                contentAlignment = Alignment.Center,
            ) {
                Glyph(g, size = 26.dp, tint = if (sel) MaterialTheme.colorScheme.onPrimaryContainer else tint)
            }
        }
    }
}
